/** 视角清单（/api/leekbox/perspectives 下发给客户端下拉用）。 */
export function perspectivesList() {
	return Object.entries(PERSPECTIVES).map(([key, p]) => ({ key, label: p.label, category: p.category, regime: p.regime }));
}

/**
 * 组装注入追问/首轮提示词的「策略视角」块。
 * @param {string} key PERSPECTIVES 的 key；空或未知返回 ""（不注入）
 * @param {string[]} signalFacts 本地代码算出的命中信号标签（确定性事实）
 */
export function buildPerspectiveBlock(key, signalFacts) {
	const p = PERSPECTIVES[key];
	if (p === void 0) return "";
	const facts =
		Array.isArray(signalFacts) && signalFacts.length > 0
			? `已命中的技术信号（本地代码实时计算，可直接引用）：${signalFacts.join("、")}。`
			: "近 120 日未命中任何内置技术信号（本地代码实时计算）。";
	return [
		`【策略视角：${p.label}】本次分析请优先采用以下战法框架审题与作答（适用场景：${p.regime}）：`,
		p.framework,
		`评分参考：${p.hints}`,
		`【本地技术面事实】${facts}`,
	].join("\n");
}
